const _id = 'plan-42km-intermediate';

TrainingWeek _w({
  required int n,
  required String focus,
  required Workout quality,
  required int easyMin,
  required double easyKm,
  required int recMin,
  required double recKm,
  required int longMin,
  required double longKm,
  String? longTitle,
  String? longStructure,
  TrainingZone longZone = TrainingZone.z2,
  String? notes,
}) {
  return TrainingWeek(
    number: n,
    focus: focus,
    notes: notes,
    workouts: [
      WB.easy(planId: _id, week: n, day: 2, min: easyMin, km: easyKm),
      quality,
      WB.recovery(planId: _id, week: n, day: 5, min: recMin, km: recKm),
      WB.longRun(
        planId: _id,
        week: n,
        day: 7,
        min: longMin,
        km: longKm,
        title: longTitle ?? 'Longão',
        structure: longStructure,
        zone: longZone,
      ),
    ],
  );
}

