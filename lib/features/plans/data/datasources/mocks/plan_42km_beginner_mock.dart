/// Helper para construir uma semana padrão de maratona iniciante:
/// segunda (easy), quarta (qualidade), quinta (recovery), domingo (long).
TrainingWeek _w({
  required int number,
  required String focus,
  required int easyMin,
  required double easyKm,
  required Workout quality,
  required int recoveryMin,
  required double recoveryKm,
  required int longMin,
  required double longKm,
  String? longTitle,
  TrainingZone longZone = TrainingZone.z2,
  WorkoutType longType = WorkoutType.longRun,
  String? longStructure,
  String? notes,
}) {
  return TrainingWeek(
    number: number,
    focus: focus,
    notes: notes,
    workouts: [
      Workout(
        id: 'p4-w$number-d2',
        dayOfWeek: 2,
        title: 'Trote leve',
        type: WorkoutType.easy,
        zone: TrainingZone.z2,
        durationMinutes: easyMin,
        distanceKm: easyKm,
        description: 'Ritmo conversável para construir base.',
      ),
      quality,
      Workout(
        id: 'p4-w$number-d5',
        dayOfWeek: 5,
        title: 'Recuperação',
        type: WorkoutType.recovery,
        zone: TrainingZone.z1,
        durationMinutes: recoveryMin,
        distanceKm: recoveryKm,
        description: 'Trote bem leve para recuperar.',
      ),
      Workout(
        id: 'p4-w$number-d7',
        dayOfWeek: 7,
        title: longTitle ?? 'Longão',
        type: longType,
        zone: longZone,
        durationMinutes: longMin,
        distanceKm: longKm,
        description: 'Construindo resistência específica.',
        structure: longStructure,
      ),
    ],
  );
}

Workout _quality({
  required int weekNumber,
  required String title,
  required WorkoutType type,
  required TrainingZone zone,
  required int minutes,
  required double km,
  required String description,
  String? structure,
}) {
  return Workout(
    id: 'p4-w$weekNumber-d4',
    dayOfWeek: 4,
    title: title,
    type: type,
    zone: zone,
    durationMinutes: minutes,
    distanceKm: km,
    description: description,
    structure: structure,
  );
}

